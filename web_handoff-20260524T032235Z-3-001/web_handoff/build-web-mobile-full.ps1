# Builds a complete web handoff zip of curatering-mobile (backend + Flutter app).
# Output: handoff/curatering-mobile-web-full-handoff.zip

$ErrorActionPreference = "Stop"
$RepoRoot = Split-Path $PSScriptRoot -Parent
$OutDir = Join-Path $PSScriptRoot "curatering-mobile-web-full"
$ZipPath = Join-Path $PSScriptRoot "curatering-mobile-web-full-handoff.zip"

$ExcludeDirNames = @(
  "node_modules", "dist", ".dart_tool", "build", ".gradle",
  ".git", ".idea", ".vscode", "coverage", ".pub-cache"
)

function Copy-TreeFiltered {
  param(
    [string]$Source,
    [string]$Dest
  )
  if (-not (Test-Path $Source)) {
    throw "Source not found: $Source"
  }
  if (Test-Path $Dest) {
    Remove-Item $Dest -Recurse -Force
  }
  New-Item -ItemType Directory -Path $Dest -Force | Out-Null

  $robocopyArgs = @(
    $Source, $Dest,
    "/E", "/NFL", "/NDL", "/NJH", "/NJS", "/NC", "/NS", "/NP",
    "/XD"
  ) + $ExcludeDirNames + @(
    "/XF", "*.apk", "*.aab", "*.ipa", ".DS_Store", "Thumbs.db"
  )
  & robocopy @robocopyArgs | Out-Null
  if ($LASTEXITCODE -ge 8) {
    throw "robocopy failed copying $Source -> $Dest (exit $LASTEXITCODE)"
  }
}

Write-Host "Preparing handoff folder..."
if (Test-Path $OutDir) { Remove-Item $OutDir -Recurse -Force }
New-Item -ItemType Directory -Path $OutDir -Force | Out-Null

Copy-TreeFiltered (Join-Path $RepoRoot "packages\backend") (Join-Path $OutDir "backend")
Copy-TreeFiltered (Join-Path $RepoRoot "packages\frontend") (Join-Path $OutDir "frontend")

Copy-Item (Join-Path $RepoRoot "README.md") (Join-Path $OutDir "README-repo-root.md") -Force -ErrorAction SilentlyContinue

$handoffDate = Get-Date -Format "yyyy-MM-dd"
$readme = @"
# Curatering Mobile — Full Web Handoff

Handoff package generated **$handoffDate**. This archive contains the **complete** mobile app codebase (Flutter client + Node/Express API) prepared for web deployment and continued development.

## Contents

| Path | Description |
|------|-------------|
| ``backend/`` | Express API (PostgreSQL). Same as ``packages/backend`` in the repo. |
| ``frontend/`` | Flutter app (customer + staff/cashier/manager). Same as ``packages/frontend``. |
| ``README-repo-root.md`` | Original monorepo readme (if present). |

Excluded from this zip (reinstall locally): ``node_modules``, ``dist``, ``.dart_tool``, ``build``, ``.gradle``.

## Backend

``````bash
cd backend
npm install
cp .env.example .env
# Edit .env — set DATABASE_URL, RESEND_API_KEY (or SMTP), etc.
npm run build
npm start
``````

Default port: **8080**. On first start, schema normalization runs against your Postgres database.

## Frontend (web)

Requires [Flutter SDK](https://docs.flutter.dev/get-started/install) (SDK ^3.11 per pubspec).

``````bash
cd frontend
flutter pub get
``````

**Customer / guest app** (restaurant ordering, catering inquiries):

``````bash
flutter run -d chrome -t lib/main_customer.dart --dart-define=API_BASE=http://localhost:8080
flutter build web -t lib/main_customer.dart --dart-define=DEFAULT_API_BASE=https://YOUR-API-HOST
``````

**Staff app** (cashier, manager, supervisor — POS login):

``````bash
flutter run -d chrome -t lib/main_staff.dart --dart-define=API_BASE=http://localhost:8080
flutter build web -t lib/main_staff.dart --dart-define=DEFAULT_API_BASE=https://YOUR-API-HOST
``````

Web output: ``frontend/build/web/`` — host statically or behind your CDN; API must be reachable with CORS (backend enables cors).

### API base URL

Set at build/run time:

- ``--dart-define=API_BASE=...`` (overrides everything)
- ``--dart-define=DEFAULT_API_BASE=...`` (production default baked into build)

If unset, release builds fall back to the production URL configured in ``lib/main.dart`` (``kProductionApiBase``).

## Roles in one codebase

- **Customer / guest**: ``main_customer.dart`` → ``forcePosLogin: false``
- **Cashier / manager / supervisor**: ``main_staff.dart`` → ``forcePosLogin: true``

Main UI logic lives in ``frontend/lib/main.dart`` (~27k lines).

## Database

PostgreSQL (not SQLite). Schema is applied via ``backend/src/db.ts`` and ``schemaNormalize.ts`` on startup. See ``backend/sql/migrations/`` for incremental SQL notes.

## Deploy checklist

1. Deploy **backend** (e.g. Railway) with ``DATABASE_URL`` and email (Resend recommended).
2. Build **two** web apps (customer + staff) or one build with separate entry/target if you use subpaths.
3. Point ``DEFAULT_API_BASE`` at the deployed API URL.
4. Verify CORS and HTTPS for payment proof uploads.

## Support files

- ``backend/.env.example`` — environment template
- ``frontend/web/`` — PWA manifest + index.html for Flutter web

